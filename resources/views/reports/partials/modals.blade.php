<script>
let currentReportModalData = null;

function openReportDetailModal(data) {
    currentReportModalData = data;
    document.getElementById('detail-report-name').textContent = data.name || 'Report Details';
    document.getElementById('detail-report-id').textContent = data.id || 'N/A';
    document.getElementById('detail-report-by').textContent = data.generated_by || '-';
    document.getElementById('detail-report-date').textContent = data.created_at || '-';
    document.getElementById('detail-report-description').textContent = data.description || 'No description provided.';

    document.getElementById('reportDetailModal').classList.remove('hidden');
    document.body.style.overflow = 'hidden';
}

function closeReportDetailModal() {
    document.getElementById('reportDetailModal').classList.add('hidden');
    if (document.getElementById('reportEditModal').classList.contains('hidden')) {
        document.body.style.overflow = '';
    }
}

function openReportEditModal(data) {
    currentReportModalData = data;
    closeReportDetailModal();

    document.getElementById('reportEditForm').action = data.update_url;
    document.getElementById('modal_edit_report_name').value = data.name || '';
    document.getElementById('modal_edit_report_description').value = data.description || '';

    document.getElementById('reportEditModal').classList.remove('hidden');
    document.body.style.overflow = 'hidden';
}

function closeReportEditModal() {
    document.getElementById('reportEditModal').classList.add('hidden');
    document.body.style.overflow = '';
}

document.addEventListener('DOMContentLoaded', function() {
    const toEditBtn = document.getElementById('detail-report-to-edit-btn');
    if (toEditBtn) {
        toEditBtn.addEventListener('click', function() {
            if (currentReportModalData) openReportEditModal(currentReportModalData);
        });
    }
    document.addEventListener('keydown', function(e) {
        if (e.key === 'Escape') {
            closeReportDetailModal();
            closeReportEditModal();
        }
    });
});
</script>
